print("   最後の世界の結果:", round(worlds[-1][1], 6), "(3 回で一周し、6 回で 2 周して元の 0.3 に戻る)")
worlds, cut = run_with_callcc(consistent_loop("stop"), max_worlds=12)
print(f"自己無撞着な値で戻り続ける: 12 世界で打ち切り={cut},  各世界が持ち込んだ値 {[w[0][0] for w in worlds]}")
